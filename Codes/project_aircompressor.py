# =========================================================
# 9. FUNCTION TO EXTRACT MEL-SPECTROGRAM WINDOWS
# =========================================================
def extract_windows_from_audio(y, label):
    X = []
    Y = []

    total_len = len(y)

    if total_len < window_size:
        return [], []

    for start in range(0, total_len - window_size + 1, n_interval):
        segment = y[start:start + window_size]

        mel = librosa.feature.melspectrogram(
            y=segment,
            sr=SR,
            n_fft=N_FFT,
            hop_length=HOP_LENGTH,
            win_length=N_FFT,
            window='hann',
            n_mels=N_MELS
        )

        feature = 2 * np.abs(mel) / N_FFT
        X.append(feature.astype(np.float32))
        Y.append(label)

    return X, Y

# =========================================================
# 10. BUILD DATASET FROM ALL FILES
# =========================================================
X_data = []
Y_data = []

for label in os.listdir(DOWNLOAD_PATH):
    label_path = os.path.join(DOWNLOAD_PATH, label)

    if not os.path.isdir(label_path):
        continue

    wav_files = [f for f in os.listdir(label_path) if f.lower().endswith(".wav")]

    for wav_file in tqdm(wav_files, desc=f"Processing {label}"):
        file_path = os.path.join(label_path, wav_file)

        try:
            y, sr = librosa.load(file_path, sr=SR)
            X_temp, Y_temp = extract_windows_from_audio(y, label)
            X_data.extend(X_temp)
            Y_data.extend(Y_temp)

        except Exception as e:
            print(f"Error processing {file_path}: {e}")

X_data = np.array(X_data)
Y_data = np.array(Y_data)

print("X_data shape:", X_data.shape)
print("Y_data shape:", Y_data.shape)

# =========================================================
# 11. CHECK LABEL DISTRIBUTION
# =========================================================
plt.figure(figsize=(6, 4))
ax = sns.countplot(x=Y_data)
