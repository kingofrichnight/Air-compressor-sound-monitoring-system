# =========================================================
# 12. ENCODE LABELS
# =========================================================
enc = LabelEncoder()
Y_encoded = enc.fit_transform(Y_data)
Y_label = to_categorical(Y_encoded)

print("Classes:", enc.classes_)
print("Encoded label shape:", Y_label.shape)

# =========================================================
# 13. TRAIN / TEST SPLIT
# =========================================================
X_train, X_test, Y_train, Y_test = train_test_split(
    X_data,
    Y_label,
    test_size=0.2,
    random_state=42,
    stratify=Y_encoded
)

print("Training data shape:", X_train.shape)
print("Testing data shape:", X_test.shape)

# =========================================================
# 14. BUILD CNN MODEL
# =========================================================
model = tf.keras.Sequential([
    layers.Reshape((X_train.shape[1], X_train.shape[2], 1), input_shape=(X_train.shape[1], X_train.shape[2])),

    layers.Conv2D(8, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(16, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2)),

    layers.Conv2D(32, (3, 3), activation='relu', padding='same'),
    layers.MaxPooling2D((2, 2)),

    layers.Flatten(),

    layers.Dense(64, activation='relu'),
    layers.Dropout(0.3),

    layers.Dense(Y_train.shape[1], activation='softmax')
])

model.summary()

# =========================================================
# 15. COMPILE MODEL
# =========================================================
BATCH_SIZE = 128
EPOCHS = 10
LEARNING_RATE = 1e-3

model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=LEARNING_RATE),
    loss='categorical_crossentropy',
    metrics=['accuracy']
)

# =========================================================
# 16. TRAIN MODEL
# =========================================================
history = model.fit(
    X_train,
    Y_train,
    validation_data=(X_test, Y_test),
    batch_size=BATCH_SIZE,
    epochs=EPOCHS,
    verbose=1
)

# =========================================================
