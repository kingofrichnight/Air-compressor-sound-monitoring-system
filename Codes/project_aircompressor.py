# 6. AUDIO / FEATURE EXTRACTION PARAMETERS
# =========================================================
SR = 48000            # Sampling rate
N_FFT = 2048          # FFT size
HOP_LENGTH = N_FFT // 4
N_MELS = 128

# MTConnect-style window setup
n_chunk = 2048
n_seq = 23
n_interval = 2048
window_size = n_chunk * n_seq   # 2048 * 23 = 47104 samples (~0.98 sec)

print("Window size in samples:", window_size)
print("Window size in seconds:", window_size / SR)

# =========================================================
# 7. OPTIONAL: VISUALIZE ONE EXAMPLE FILE
# =========================================================
def plot_wave_and_mel(file_path, title_text="Audio"):
    y, sr = librosa.load(file_path, sr=SR)

    mel = librosa.feature.melspectrogram(
        y=y, sr=sr,
        n_fft=N_FFT,
        hop_length=HOP_LENGTH,
        win_length=N_FFT,
        window='hann',
        n_mels=N_MELS
    )

    fig, ax = plt.subplots(1, 2, figsize=(15, 4))

    librosa.display.waveshow(y, sr=sr, ax=ax[0])
    ax[0].set_title(f"{title_text}: Time Domain")
    ax[0].set_xlabel("Time [sec]")
    ax[0].set_ylabel("Amplitude")
    ax[0].set_ylim([-1, 1])

    img = librosa.display.specshow(
        librosa.power_to_db(2 * np.abs(mel) / N_FFT, ref=1),
        ax=ax[1],
        x_axis='time',
        y_axis='mel',
        sr=sr,
        vmin=-80,
        vmax=0
    )
    ax[1].set_title(f"{title_text}: Mel-Spectrogram")
    ax[1].set_xlabel("Time [sec]")
    ax[1].set_ylabel("Mel Frequency")

    fig.colorbar(img, ax=ax[1], format="%+2.0f dB")
    plt.tight_layout()
    plt.show()

