# 4. DOWNLOAD ALL WAV FILES FROM EACH GITHUB FOLDER
# =========================================================
def download_folder_from_github(folder_name, label_name):
    """
    Downloads all .wav files from a GitHub folder using GitHub Contents API.
    """
    url = f"{BASE_API}/{folder_name}"
    response = requests.get(url)

    if response.status_code != 200:
        print(f"Failed to access folder: {folder_name}")
        print("Status code:", response.status_code)
        print("Response:", response.text)
        return

    files = response.json()
    save_dir = os.path.join(DOWNLOAD_PATH, label_name)
    os.makedirs(save_dir, exist_ok=True)

    wav_count = 0
    for file in tqdm(files, desc=f"Downloading {label_name}"):
        if isinstance(file, dict) and file.get("name", "").lower().endswith(".wav"):
            download_url = file.get("download_url")
            file_path = os.path.join(save_dir, file["name"])

            r = requests.get(download_url)
            if r.status_code == 200:
                with open(file_path, "wb") as f:
                    f.write(r.content)
                wav_count += 1

    print(f"{label_name}: downloaded {wav_count} wav files")


